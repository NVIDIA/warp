from enum import IntEnum
from typing import Any, Literal

import warp as wp
from warp._src.fem.polynomial import Polynomial, quadrature_1d
from warp._src.fem.types import Coords, Coords_f64, make_coords

TetrahedronQuadratureFamily = Literal["xiao_gimbutas", "witherden_vincent"]
"""Named families of tabulated tetrahedral quadrature rules."""

QuadratureFamily = Polynomial | TetrahedronQuadratureFamily
"""Quadrature families accepted by :meth:`PrototypeElement.instantiate_quadrature`."""

_vec1 = wp.types.vector(length=1, dtype=float)
_vec1d = wp.types.vector(length=1, dtype=wp.float64)


class Element(IntEnum):
    """Enumeration of reference element types."""

    LINE_SEGMENT = 1
    """Line segment reference element."""
    SQUARE = 2
    """Quadrilateral reference element."""
    CUBE = 3
    """Hexahedral reference element."""
    TRIANGLE = 4
    """Triangular reference element."""
    TETRAHEDRON = 5
    """Tetrahedral reference element."""

    @property
    def prototype(self) -> "PrototypeElement":
        """Prototype element for the given element type"""
        return {
            Element.LINE_SEGMENT: LinearEdge,
            Element.SQUARE: Square,
            Element.CUBE: Cube,
            Element.TRIANGLE: Triangle,
            Element.TETRAHEDRON: Tetrahedron,
        }[self]


class PrototypeElement:
    dimension = 0
    """Intrinsic dimension of the element."""

    @staticmethod
    def measure() -> float:
        """Measure (area, volume, ...) of the reference element"""
        raise NotImplementedError

    @staticmethod
    def instantiate_quadrature(
        order: int, family: QuadratureFamily | None
    ) -> tuple[list[tuple[float, ...]], list[float]]:
        """Return a quadrature of a given order for a prototypical element.

        Args:
            order: Polynomial degree to integrate exactly.
            family: Quadrature family, or ``None`` for the element's default rule.

        Returns:
            Tuple of (points, weights) where points are tuples of Python floats (fp64-safe)
            and weights are Python floats.
        """
        raise NotImplementedError

    @classmethod
    def center(cls):
        """Return the coordinates for the center of the element."""
        coords, _ = cls.instantiate_quadrature(order=0, family=None)
        return coords[0]

    @wp.func
    def project(v: Any):
        """Project coordinates so that they belong to the element."""
        return wp.min(wp.max(v, type(v)(v.dtype(0.0))), type(v)(v.dtype(1.0)))

    @wp.func
    def ref_delta(coord_delta: Any):
        """Transform an element coordinates delta to reference space"""
        return coord_delta

    @wp.func
    def coord_delta(ref_delta: Any):
        """Transform a delta in reference space to element coords (identity for 3D)"""
        return ref_delta

    @wp.func
    def coord_delta(ref_delta: wp.vec2):
        """Transform a delta in reference space to element coords"""
        return make_coords(ref_delta[0], ref_delta[1])

    @wp.func
    def coord_delta(ref_delta: wp.vec2d):
        return make_coords(ref_delta[0], ref_delta[1])

    @wp.func
    def coord_delta(ref_delta: _vec1):
        """Transform a delta in reference space to element coords"""
        return make_coords(ref_delta[0])

    @wp.func
    def coord_delta(ref_delta: _vec1d):
        return make_coords(ref_delta[0])


def _point_count_from_order(order: int, family: Polynomial):
    if family == Polynomial.GAUSS_LEGENDRE:
        point_count = max(1, order // 2 + 1)
    elif family == Polynomial.LOBATTO_GAUSS_LEGENDRE:
        point_count = max(2, order // 2 + 2)
    elif family == Polynomial.EQUISPACED_CLOSED:
        point_count = max(2, 2 * (order // 2) + 1)
    elif family == Polynomial.EQUISPACED_OPEN:
        point_count = max(1, 2 * (order // 2) + 1)
    else:
        raise ValueError(
            f"Unsupported quadrature family {family!r} for this element; expected a Polynomial"
            " (the 'xiao_gimbutas' and 'witherden_vincent' families are only available for tetrahedra)"
        )

    return point_count


class Cube(PrototypeElement):
    dimension = 3

    @staticmethod
    def measure() -> float:
        return 1.0

    @staticmethod
    def instantiate_quadrature(order: int, family: QuadratureFamily | None):
        if family is None:
            family = Polynomial.GAUSS_LEGENDRE

        point_count = _point_count_from_order(order=order, family=family)
        gauss_1d, weights_1d = quadrature_1d(point_count=point_count, family=family)

        coords = [(x, y, z) for x in gauss_1d for y in gauss_1d for z in gauss_1d]
        weights = [wx * wy * wz for wx in weights_1d for wy in weights_1d for wz in weights_1d]

        return coords, weights


class Square(PrototypeElement):
    dimension = 2

    @staticmethod
    def measure() -> float:
        return 1.0

    @staticmethod
    def instantiate_quadrature(order: int, family: QuadratureFamily | None):
        if family is None:
            family = Polynomial.GAUSS_LEGENDRE

        point_count = _point_count_from_order(order=order, family=family)
        gauss_1d, weights_1d = quadrature_1d(point_count=point_count, family=family)

        coords = [(x, y, 0.0) for x in gauss_1d for y in gauss_1d]
        weights = [wx * wy for wx in weights_1d for wy in weights_1d]

        return coords, weights

    @wp.func
    def ref_delta(coord_delta: Coords):
        return wp.vec2(coord_delta[0], coord_delta[1])

    @wp.func
    def ref_delta(coord_delta: Coords_f64):
        return wp.vec2d(coord_delta[0], coord_delta[1])


class LinearEdge(PrototypeElement):
    dimension = 1

    @staticmethod
    def measure() -> float:
        return 1.0

    @staticmethod
    def instantiate_quadrature(order: int, family: QuadratureFamily | None):
        if family is None:
            family = Polynomial.GAUSS_LEGENDRE

        point_count = _point_count_from_order(order=order, family=family)
        gauss_1d, weights_1d = quadrature_1d(point_count=point_count, family=family)

        coords = [(x, 0.0, 0.0) for x in gauss_1d]
        return coords, weights_1d

    @wp.func
    def ref_delta(coord_delta: Coords):
        return _vec1(coord_delta[0])

    @wp.func
    def ref_delta(coord_delta: Coords_f64):
        return _vec1d(coord_delta[0])


