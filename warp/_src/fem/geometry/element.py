    @wp.func
    def project(v: Any):
        z = v.dtype(0.0)
        o = v.dtype(1.0)
        h = v.dtype(0.5)
        n = wp.max(z, (v[0] + v[1] - o) * h)
        a = wp.clamp(v[0] - n, z, o)
        b = wp.clamp(v[1] - n, z, o)
        return type(v)(a, b, o - (a + b))

    @wp.func
    def coord_delta(ref_delta: wp.vec2):
        return make_coords(-ref_delta[0] - ref_delta[1], ref_delta[0], ref_delta[1])

