class Tetrahedron(PrototypeElement):
    dimension = 3

    @staticmethod
    def measure() -> float:
        return 1.0 / 6.0

    @staticmethod
    def instantiate_quadrature(order: int, family: QuadratureFamily | None):
        if family == "witherden_vincent":
            if order > 10:
                raise NotImplementedError(
                    f"Witherden-Vincent tetrahedron quadrature is available up to order 10, got {order}"
                )
            coords, weights = WITHERDEN_VINCENT_QUADRATURE[max(order, 1)]
            return list(coords), list(weights)
        if family is not None and family != "xiao_gimbutas":
            # Duffy transformation from cube to tetrahedron
            # The Jacobian (1 - x)^2 (1 - y) adds up to two degrees to the integrand
            point_count = _point_count_from_order(order=order + 2, family=family)
            gauss_1d, weights_1d = quadrature_1d(point_count=point_count, family=family)

            coords = [
                (x, y * (1.0 - x), z * (1.0 - x) * (1.0 - y)) for x in gauss_1d for y in gauss_1d for z in gauss_1d
            ]

            # Scale weight by 6.0 so that they sum up to 1
            weights = [
                6.0 * wx * wy * wz * (1.0 - x) * (1.0 - x) * (1.0 - y)
                for x, wx in zip(gauss_1d, weights_1d, strict=True)
                for y, wy in zip(gauss_1d, weights_1d, strict=True)
                for wz in weights_1d
            ]

            return coords, weights

        # Default ("xiao_gimbutas"): centroid and symmetric 4-point rules for orders <= 2,
        # then the tabulated Xiao and Gimbutas rules

        if order <= 1:
            weights = [1.0]
            coords = [(1.0 / 4.0, 1.0 / 4.0, 1.0 / 4.0)]
        elif order <= 2:
            weights = [1.0 / 4.0, 1.0 / 4.0, 1.0 / 4.0, 1.0 / 4.0]
            coords = [
                (0.1381966011250110, 0.1381966011250110, 0.1381966011250110),
                (0.5854101966249680, 0.1381966011250110, 0.1381966011250110),
                (0.1381966011250110, 0.5854101966249680, 0.1381966011250110),
                (0.1381966011250110, 0.1381966011250110, 0.5854101966249680),
            ]
        elif order <= 10:
            coords, weights = XIAO_GIMBUTAS_QUADRATURE[order]
            coords, weights = list(coords), list(weights)
        else:
            raise NotImplementedError(f"Tetrahedron quadrature is available up to order 10, got {order}")

        return coords, weights

    @wp.func
    def project(v: Any):
        z = v.dtype(0.0)
        o = v.dtype(1.0)
        h = v.dtype(0.5)
        t = v.dtype(1.0 / 3.0)

        # project on 1-2-3 half-space
        n = wp.max(z, (v[0] + v[1] + v[2] - o) * t)
        c = v - type(v)(n)

        # project on 1-2, 2-3, 3-1 half-spaces
        n = wp.max(z, (c[0] + c[1] - o) * h)
        c = c - type(v)(n, n, z)
        n = wp.max(z, (c[1] + c[2] - o) * h)
        c = c - type(v)(z, n, n)
        n = wp.max(z, (c[2] + c[0] - o) * h)
        c = c - type(v)(n, z, n)

        # project on cube
        return PrototypeElement.project(c)
